"""Блокировки, общие для нескольких эндпоинтов."""
from __future__ import annotations

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.models.user import User


async def lock_user(db: AsyncSession, user_id: int) -> None:
    """Взять блокировку строки пользователя до конца транзакции.

    Нужна там, где решение принимается по данным, разбросанным по нескольким
    строкам, и блокировка одной строки не спасает. Пример: XP за тест. Набор
    вопросов лежит в своей сессии, и два параллельных запроса по РАЗНЫМ
    сессиям одной книги блокируют разные строки — то есть не мешают друг
    другу вовсе. Оба видят «раньше не сдавал» и оба начисляют XP.

    Блокировка пользователя выстраивает такие запросы в очередь: второй
    читает уже зафиксированный результат первого.
    """
    await db.execute(select(User.id).where(User.id == user_id).with_for_update())
